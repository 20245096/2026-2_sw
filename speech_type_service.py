from services.question_service import is_question
def classify_speech_type(sentence):

    s = sentence.strip()

    if "박수" in s and ("볼까요" in s or "쳐볼게요" in s):
        return "지시 발화"
    
    if "박수" in s and ("쳐줄게요" in s or "쳐줄까요" in s):
        return "지시 발화"

    if "나와서 해볼게요" in s:
        return "지시 발화"
    
    if "나와서 해볼까요" in s:
        return "지시 발화"

    if ("모둠" in s or "조" in s) and "나올게요" in s:
        return "지시 발화"

    directive_patterns = [
        "해보세요", "해봅시다", "해주세요", "보세요", "봐주세요", 
        "생각해보세요", "생각해 봅시다", "찾아보세요",
        "적어보세요", "말해보세요",
        "읽어보세요", "읽어봅시다", "정리해보세요", "정리해 봅시다", 
        "활동해봅시다",
        "시작해봅시다", "시작하도록 하세요", "활동 시작하도록 하세요",
        "발표해볼까요", "발표해 봅시다",
        "생각해볼까요", 
        "같이 해볼까요",
        "찾아볼까요",
        "적어볼까요",
        "시작!", "시작하세요", "시작합시다",
        "발표해 줄 친구", "발표할 친구",
        "손들 친구",
        "읽어볼 친구",
        "나와볼 친구",
        "대답해볼 친구", "말해볼 친구",
        "읽어봅시다",
        "펴봅시다",
        "말해봅시다"
    ]

    reaction_patterns = [
        "네", "자", "어", "음"
    ]

    feedback_patterns = [
        "잘했", "잘했어요", "잘했습니다",
        "잘 이야기", "잘 이야기해줬", "잘 얘기", "잘 발표했", "이야기해주셨",
        "좋은 의견", "좋은 생각", "좋은 답", "좋은 발표", "발표해주셨",
        "좋은 근거", "좋은 질문",
        "아주 잘", "잘 생각했", "잘 참여했", "잘 봐줬",
        "훌륭",
        "맞아요", "맞습니다", "그렇죠",
        "보기 좋아",
        "참여하는 모습",
        "적극적으로",
        "잘하고 있",
        "고마운 것 같아요",
        "좋습니다", "좋아요", "좋은 것 같", "잘한 것 같",
        "고맙습니다", "감사합니다", "고맙고", "고마워",
        "잘 읽어줬", "잘 말해줬", "잘 말해주었", "잘 발표", "잘 설명했", "잘 설명해줬", "잘 설명해주었", "설명을 잘했",
        "잘 들어줬", "잘 들었어요",
        "잘 찾아줬", "잘 찾아봤",
        "잘 참여", "잘 조사",
        "잘 만들어",
        "잘 정리", "잘 정리했",
        "잘 기억", "잘 기억하고",
        "집중해서",
        "큰 목소리로 읽어",
        "열심히",
        "수고", "수고 많", "수고했", "고생했", "고생 많",
        "확인했습니다",
        "공유해준",
        "찾아주셨", "잘 찾아",
        "잘 해왔", "잘 해온"
    ]

    etc = s.replace(".", "").replace("!", "").replace("?", "").strip()

    if etc in reaction_patterns:
        return "기타 발화"
    
    if s.strip() in [
        "오!", "오!!", "오~",
        "와!", "와!!", "와~",
        "오오!", "오호!"
    ]:
        return "피드백 발화"

    if (
        any(p in s for p in feedback_patterns)
        and not any(p in s for p in [
            "설명했듯이",
            "앞에서 설명",
            "방금 설명", "아까 설명",
            "제가 설명", "선생님이 설명",
            "설명할 수 있는 사람",
            "말할 수 있는 사람", "대답할 수 있는 사람",
            "발표할 사람",
            "있는 친구"
        ])
    ):
        return "피드백 발화"

    if any(p in s for p in directive_patterns):
        return "지시 발화"
    
    if (
        ("무엇인지" in s or "어떻게" in s or "어떤 것인지" in s or "왜인지" in s)
        and any(e in s for e in [
            "입니다",
            "합니다",
            "활동입니다",
            "의미합니다",
            "설명하겠습니다",
            "소개하겠습니다",
            "알아보겠습니다",
            "정리하겠습니다"
        ])
    ):
        return "설명 발화"

    if is_question(s):
        return "질문 발화"

    return "설명 발화"

def speech_color(speech_type):

    colors = {
        "설명 발화": "#e74a3b",
        "질문 발화": "#4e73df",
        "피드백 발화": "#1cc88a",
        "지시 발화": "#f6c23e"
    }

    return colors.get(speech_type, "#555")